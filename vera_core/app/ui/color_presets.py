DEFAULT = "jet"
_BY_NAME = dict(PRESETS)


def rgb_points(name):
    """Control points for a preset, falling back to the default."""
    return _BY_NAME.get(name, _BY_NAME[DEFAULT])


def css_gradient(name):
    stops = ", ".join(
        f"rgb({r * 255:.0f},{g * 255:.0f},{b * 255:.0f}) {t * 100:.1f}%"
        for t, r, g, b in rgb_points(name)
    )
    return f"linear-gradient(to right, {stops})"
